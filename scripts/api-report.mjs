// API report of the published packages: for each entry point of `exports`,
// the declarations it exports, read from the built `.d.ts` files with the
// TypeScript compiler. Written to `packages/<package>/api/<entry>.api.md`,
// which are committed, so that a change of the public API shows in the diff
// of a pull request. Run after `pnpm build`.
//
//   node scripts/api-report.mjs          writes the reports (pnpm api:update)
//   node scripts/api-report.mjs --check  fails if they are out of date
//                                        (pnpm api:check)
//
// Each report lists the exported declarations, sorted by name, without their
// comments, then the declarations that are not exported but that the
// exported ones refer to: their shape is part of the API too. Declarations
// exported by another entry point of the same package are left to the report
// of that entry point. Types of other packages are only named, with the
// package they come from.
import { spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'
import ts from 'typescript'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')

const HEADER =
  '<!-- Generated by scripts/api-report.mjs from the built declarations. Do not edit: run `pnpm build && pnpm api:update`. -->'

const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** The entry points of a package that have types: `.` and `./<name>`. */
const entriesOf = (dir, manifest) =>
  Object.entries(manifest.exports ?? {}).flatMap(([subpath, target]) => {
    const types = typeof target === 'object' ? target.types : undefined
    if (typeof types !== 'string') return []
    const name =
      subpath === '.' ? 'index' : subpath.slice(2).replaceAll('/', '-')
    return [
      {
        subpath,
        name,
        specifier: manifest.name + subpath.slice(1),
        file: join(dir, types),
      },
    ]
  })

/** The package of a declaration file outside the package, for its name. */
const packageOf = (file) => {
  const parts = file.split(sep)
  const index = parts.lastIndexOf('node_modules')
  if (index !== -1) {
    const scoped = parts[index + 1].startsWith('@')
    return parts.slice(index + 1, index + (scoped ? 3 : 2)).join('/')
  }
  const inPackages = relative(join(root, 'packages'), file).split(sep)
  if (inPackages[0] !== '..') return `@dotpress/${inPackages[0]}`
  if (/[/\\]typescript[/\\]lib[/\\]/.test(file)) return 'typescript'
  return relative(root, file)
}

/** A top-level declaration: of a file, or of a top-level namespace. */
const isTopLevel = (node) => {
  const parent =
    ts.isVariableDeclaration(node) && ts.isVariableDeclarationList(node.parent)
      ? node.parent.parent.parent
      : node.parent
  return parent !== undefined && ts.isSourceFile(parent)
}

const printer = ts.createPrinter({ removeComments: true })

/** The text of a declaration, without `export` and `default`. */
const print = (node) => {
  const file = node.getSourceFile()
  if (ts.isVariableDeclaration(node)) {
    const list = node.parent
    const keyword =
      list.flags & ts.NodeFlags.Const
        ? 'const'
        : list.flags & ts.NodeFlags.Let
          ? 'let'
          : 'var'
    const text = printer.printNode(ts.EmitHint.Unspecified, node, file)
    return `declare ${keyword} ${text};`
  }
  return printer
    .printNode(ts.EmitHint.Unspecified, node, file)
    .replace(/^export (default )?/, '')
}

const resolve = (checker, symbol) =>
  symbol.flags & ts.SymbolFlags.Alias
    ? checker.getAliasedSymbol(symbol)
    : symbol

/** The reports of the entry points of a package, by file name. */
const reportPackage = async (dir) => {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const entries = entriesOf(dir, manifest)
  if (entries.length === 0) return new Map()
  for (const entry of entries) {
    if (!existsSync(entry.file)) {
      throw new Error(`${entry.file} is missing: run \`pnpm build\` first.`)
    }
  }
  const dist = realpathSync(join(dir, 'dist')) + sep
  const program = ts.createProgram(
    entries.map((entry) => entry.file),
    {
      noEmit: true,
      skipLibCheck: true,
      strict: true,
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.NodeNext,
      moduleResolution: ts.ModuleResolutionKind.NodeNext,
    }
  )
  const checker = program.getTypeChecker()
  const own = (declaration) =>
    realpathSync(declaration.getSourceFile().fileName).startsWith(dist)

  // The exports of each entry point, and the entry point of each declaration
  // exported by one.
  const exported = new Map()
  const exportsOf = new Map()
  for (const entry of entries) {
    const file = program.getSourceFile(entry.file)
    const module = file && checker.getSymbolAtLocation(file)
    if (!module) throw new Error(`${entry.file} is not a module.`)
    const list = checker
      .getExportsOfModule(module)
      .map((symbol) => ({
        name: symbol.name,
        symbol: resolve(checker, symbol),
      }))
      .sort((a, b) => compare(a.name, b.name))
    for (const { symbol } of list) {
      for (const declaration of symbol.declarations ?? []) {
        if (!exported.has(declaration)) exported.set(declaration, entry)
      }
    }
    exportsOf.set(entry, list)
  }

  const reports = new Map()
  for (const entry of entries) {
    const blocks = []
    const external = new Map()
    const imports = new Map()
    const internal = []
    const seen = new Set()
    const names = new Set(exportsOf.get(entry).map(({ name }) => name))

    const add = (map, key, name) => {
      if (!map.has(key)) map.set(key, new Set())
      map.get(key).add(name)
    }

    // The declarations a node refers to: the own ones that the package does
    // not export are reported after the exports, the others are imported.
    const visit = (node) => {
      if (ts.isIdentifier(node)) {
        const symbol = checker.getSymbolAtLocation(node)
        const target = symbol && resolve(checker, symbol)
        const declaration = target?.declarations?.[0]
        if (declaration && isTopLevel(declaration)) {
          const from = exported.get(declaration)
          if (!own(declaration)) {
            const file = realpathSync(declaration.getSourceFile().fileName)
            if (!file.includes(`${sep}typescript${sep}lib${sep}`)) {
              add(imports, packageOf(file), node.text)
            }
          } else if (from === undefined) {
            for (const each of target.declarations) {
              if (seen.has(each)) continue
              seen.add(each)
              internal.push({ name: target.name, declaration: each })
            }
          } else if (from !== entry && !names.has(node.text)) {
            add(imports, from.specifier, node.text)
          }
        }
      }
      ts.forEachChild(node, visit)
    }

    for (const { name, symbol } of exportsOf.get(entry)) {
      const declarations = symbol.declarations ?? []
      const local = declarations.filter(own)
      if (local.length === 0) {
        const from = declarations.length
          ? packageOf(realpathSync(declarations[0].getSourceFile().fileName))
          : 'unknown'
        add(external, from, name)
        continue
      }
      const texts = local.map((declaration) => `export ${print(declaration)}`)
      if (symbol.name !== name) {
        texts.push(`export { ${symbol.name} as ${name} };`)
      }
      blocks.push(texts.join('\n'))
      local.forEach(visit)
    }
    // The declarations found while visiting are visited in turn.
    for (let index = 0; index < internal.length; index++) {
      visit(internal[index].declaration)
    }

    const statements = (map, keyword) =>
      [...map]
        .sort(([a], [b]) => compare(a, b))
        .map(
          ([from, list]) =>
            `${keyword} { ${[...list].sort(compare).join(', ')} } from '${from}';`
        )
    // Re-exported types need no import.
    for (const [from, list] of external) {
      for (const name of list) imports.get(from)?.delete(name)
      if (imports.get(from)?.size === 0) imports.delete(from)
    }
    const head = [
      ...statements(imports, 'import type'),
      ...statements(external, 'export'),
    ]
    const sections = [
      `# ${entry.specifier}`,
      HEADER,
      '## Exports',
      '```ts\n' +
        (head.length ? head.join('\n') + '\n\n' : '') +
        blocks.join('\n\n') +
        '\n```',
    ]
    if (internal.length > 0) {
      sections.push(
        '## Not exported',
        'Declarations that the exports refer to, without exporting them.',
        '```ts\n' +
          internal
            .sort((a, b) => compare(a.name, b.name))
            .map(({ declaration }) => print(declaration))
            .join('\n\n') +
          '\n```'
      )
    }
    const markdown = await prettier.format(sections.join('\n\n') + '\n', {
      ...(await prettier.resolveConfig(join(root, 'package.json'))),
      parser: 'markdown',
    })
    reports.set(`${entry.name}.api.md`, markdown)
  }
  return reports
}

let outdated = 0
for (const name of readdirSync(join(root, 'packages')).sort()) {
  const dir = join(root, 'packages', name)
  if (!existsSync(join(dir, 'package.json'))) continue
  const reports = await reportPackage(dir)
  const apiDir = join(dir, 'api')
  const existing = existsSync(apiDir)
    ? readdirSync(apiDir).filter((file) => file.endsWith('.api.md'))
    : []
  for (const file of existing) {
    if (reports.has(file)) continue
    const path = relative(root, join(apiDir, file))
    if (check) {
      console.error(`${path}: no such entry point anymore.`)
      outdated++
    } else {
      rmSync(join(apiDir, file))
      console.log(`${path}: removed.`)
    }
  }
  for (const [file, markdown] of reports) {
    const path = join(apiDir, file)
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    if (current === markdown) continue
    if (check) {
      console.error(`${relative(root, path)}: out of date.`)
      const scratch = mkdtempSync(join(tmpdir(), 'api-report-'))
      writeFileSync(join(scratch, file), markdown)
      spawnSync(
        'diff',
        [
          '-u',
          '--label',
          relative(root, path),
          '--label',
          `${relative(root, path)} (built)`,
          current === undefined ? '/dev/null' : path,
          join(scratch, file),
        ],
        { stdio: 'inherit' }
      )
      rmSync(scratch, { recursive: true })
      outdated++
    } else {
      mkdirSync(apiDir, { recursive: true })
      writeFileSync(path, markdown)
      console.log(
        `${relative(root, path)}: ${current ? 'updated' : 'created'}.`
      )
    }
  }
}

if (check && outdated > 0) {
  console.error(
    `\n${outdated} API report(s) out of date. If the change of the API is intended, run \`pnpm build && pnpm api:update\` and commit the reports.`
  )
  process.exit(1)
}
if (check) console.log('API reports up to date.')
